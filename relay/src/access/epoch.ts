/**
 * 访问权限的「纪元」计数。
 *
 * ── 要解决的问题 ────────────────────────────────────────────────
 *
 * 管理员随时可能在后台改某个账号的设备归属或能力开关。
 * 此时**已经连着的 WebSocket 必须立刻失去相应权限**，
 * 而不是等到连接断开或会话过期——否则管理页面的勾选框就只是个装饰。
 *
 * ── 做法 ──────────────────────────────────────────────────────
 *
 * 不用「把权限快照进连接」，而是每个连接缓存一份解析结果，
 * 并记录当时的纪元号。任何影响访问控制的变更都让纪元 +1，
 * 于是所有缓存**自动失效**，下一条消息就会重新查库。
 *
 * 这样既满足了「即刻生效」，又避免了每条输入消息都查三次库
 * （拖动时输入可达每秒数十条）。
 *
 * relay 是单进程，模块级变量即全局单例，无需跨进程同步。
 */

let epoch = 0;

/** 影响访问控制的变更发生后调用。 */
export function bumpAccessEpoch(): void {
  epoch += 1;
}

/** 当前纪元号。 */
export function getAccessEpoch(): number {
  return epoch;
}
